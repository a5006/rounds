import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { PLAN_TEMPLATES } from '../src/core/plans.mjs';
import { audioKey } from '../src/core/audio-cache.mjs';
import { createWorkoutPlan } from '../src/core/mobile-core.mjs';
import { decodeWav, wavChunks } from '../src/core/pcm.mjs';
const run = promisify(execFile);
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const out = path.join(root, 'assets/audio-presets'), temp = path.join(root, '.preset-audio-work');
await fs.mkdir(out, { recursive: true }); await fs.mkdir(temp, { recursive: true });
const clips = {};
for (const name of await fs.readdir(path.join(root, 'assets/audio'))) if (name.endsWith('.wav')) clips[name.slice(0, -4)] = decodeWav(await fs.readFile(path.join(root, 'assets/audio', name)));
const manifest = [], info = [];
for (const template of PLAN_TEMPLATES) for (const voiceAudio of [true, false]) for (const earlyWarning of [true, false]) {
  const key = audioKey(template.config, { voiceAudio, earlyWarning });
  const plan = createWorkoutPlan(template.config, { voiceAudio, earlyWarning });
  const wav = path.join(temp, `${key}.wav`), m4a = path.join(out, `${key}.m4a`);
  const handle = await fs.open(wav, 'w');
  try { for (const chunk of wavChunks(plan, clips)) await handle.write(chunk); } finally { await handle.close(); }
  try {
    await run(process.env.FFMPEG_PATH || 'ffmpeg', ['-nostdin', '-hide_banner', '-loglevel', 'error', '-y', '-i', wav, '-c:a', 'aac', '-b:a', '32k', '-ar', '22050', '-movflags', '+faststart', m4a]);
    const { stdout } = await run(process.env.FFPROBE_PATH || 'ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'json', m4a]);
    const duration = Number(JSON.parse(stdout).format.duration), expected = plan.reduce((sum, phase) => sum + phase.durationMs, 0) / 1000;
    if (Math.abs(duration - expected) > .05) throw new Error(`Preset duration mismatch: ${key} ${duration} / ${expected}`);
    info.push({ key, preset: template.id, bytes: (await fs.stat(m4a)).size, duration, expected });
    manifest.push(`  '${key}': require('../assets/audio-presets/${key}.m4a'),`);
    console.log(`Prepared ${template.id} speech=${voiceAudio} warning=${earlyWarning}: ${duration}s`);
  } finally { await fs.unlink(wav); }
}
await fs.writeFile(path.join(root, 'src/preset-audio-assets.ts'), `// Generated by scripts/generate-preset-audio.mjs. All preset sound combinations.\nexport const presetAudioAssets: Record<string, number> = {\n${manifest.join('\n')}\n};\n`);
await fs.writeFile(path.join(out, 'manifest.json'), JSON.stringify(info, null, 2));
console.log(`16 preset variants: ${info.reduce((sum, item) => sum + item.bytes, 0)} bytes total`);
